#!/usr/bin/env python3
"""EXPLORATORY (data already seen): adaptive-allocation versions of the E1b / E5 pool tests.

Question B1/B3: does ADAPTIVE allocation (spend episodes on promising challengers, as in
Sandoval, Waudby-Smith & Jordan 2026, arXiv:2603.17925) cut the EPISODES needed while staying valid?

Everything here is batched over simulations (axis 0) with numpy.  No API calls.

B1, adaptive efficacy.  H0: no challenger beats the incumbent.
    Paired step: draw a fresh task, run the incumbent and ONE chosen challenger k on it
    (2 episodes).  Challenger k keeps the E1b one-sided hedged-capital process K+_k on discordant
    outcomes (X = 1 if k succeeds and the incumbent fails); only the sampled arm's process moves.
    Global e-value = uniform average over challengers of their current capitals.

    Why this is a valid e-process under adaptive, predictable arm selection.  Let F_t be the
    filtration generated by everything seen so far (arm choices, tasks, outcomes).  The arm A_t
    chosen at step t and every bet lambda_{k,t} are F_{t-1}-measurable (predictable).  Under H0
    every challenger k has P(X=1 | discordant, F_{t-1}, A_t = k) <= 1/2, so for the sampled arm
    E[1 + lambda (X - 1/2) | F_{t-1}] <= 1, and for every unsampled arm the factor is exactly 1.
    Hence each capital K+_{k,t} is a nonnegative supermartingale with start 1 in the JOINT
    filtration, whatever the (predictable) selection rule is.  A fixed-weight average of
    supermartingales is a supermartingale, so the uniform average is an e-process and Ville gives
    P(sup_t E_t >= 1/alpha) <= alpha.  Selection may depend on the capitals themselves: it only
    changes WHICH supermartingale is allowed to move, never the sign of its drift.  Fresh tasks
    at every step keep the "conditional on the past" null intact.

    Cost of the plain average: to reject, ONE arm needs capital >= K / alpha.

B3, adaptive futility with drop-the-loser.  H0 = union (some challenger is >= delta better).
    Per-challenger downward e-process from E5 (``futility_eprocess``).  A challenger is dropped
    (no longer run) once its own e-process >= 1/alpha.  Pool certified when all are dropped.
    Validity: if some k* satisfies H0_k*, the event "all dropped" implies "k* dropped", and a
    dropped arm's crossing has probability <= alpha by Ville for the supermartingale K_k*
    (its stopped value is also a supermartingale when the arm stops being run).

Rules (B1):  rr (round robin), greedy (argmax log-capital, ties random, eps=0.1 uniform
exploration), ucb (win rate among discordant pairs + bonus), thompson (Beta posterior on that win
rate), audit (all K challengers + incumbent on every task, K+1 episodes per task).
Rules (B3):  audit (E5, no dropping, certify when min_k E_k >= 1/alpha), drop (incumbent + all
still-active arms), focus (incumbent + the active arm with the LOWEST log-capital).
"""

