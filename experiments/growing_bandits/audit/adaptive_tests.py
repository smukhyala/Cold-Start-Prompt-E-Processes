def rate_at(ep: np.ndarray, budget: float) -> float:
    count = 0
    for v in ep:
        if v <= budget:
            count += 1
    return count / len(ep)


def rate_finite(ep: np.ndarray) -> float:
    count = 0
    for v in ep:
        if np.isfinite(v):
            count += 1
    return count / len(ep)
