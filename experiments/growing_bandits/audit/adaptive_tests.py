def load_task_difficulty(path: Path | None = None) -> np.ndarray:
    """Per-task mean success over arms of G (replicate 0), clipped to [0.01, 0.99]."""
    if path is None:
        path = MATRICES / "G.csv"
    df = pd.read_csv(path)
    df = df[df["replicate"] == 0]
    q = df.groupby("task_id")["success"].mean().to_numpy(dtype=float)
    return np.clip(q, 0.01, 0.99)


def mean_gain(q_grid: np.ndarray, shift: float, lo: float, hi: float) -> float:
    total = 0.0
    for q in q_grid:
        total = total + (min(max(q + shift, lo), hi) - q)
    return total / len(q_grid)


def build_shifts(scenario: str, K: int, B: int, delta: float, rng: np.random.Generator,
                 q_grid: np.ndarray | None = None):
    """Per-simulation, per-challenger success-probability shifts and the 'good arm' mask.

    Scenarios: null, good1 (one arm at +delta), good3 (three arms at +delta), below (half the
    arms at -0.15), boundary (one arm whose MEAN gain is exactly delta despite clipping; B3
    validity).  Arm positions are re-randomised in every simulation.
    """
    shifts = np.zeros((B, K))
    good = np.zeros((B, K), dtype=bool)
    for b in range(B):
        perm = rng.permutation(K)
        if scenario == "null":
            continue
        if scenario == "good1":
            shifts[b, perm[0]] = delta
            good[b, perm[0]] = True
        elif scenario == "good3":
            for j in range(3):
                shifts[b, perm[j]] = delta
                good[b, perm[j]] = True
        elif scenario == "below":
            for j in range(K // 2):
                shifts[b, perm[j]] = -0.15
        elif scenario == "boundary":
            s = fu.boundary_shift(q_grid, delta)
            shifts[b, perm[0]] = s
            good[b, perm[0]] = True
        else:
            raise ValueError(scenario)
    return shifts, good


def draw_task(rng: np.random.Generator, q_grid: np.ndarray, B: int, K: int, shifts: np.ndarray,
              lo: float, hi: float):
    """Fresh task per simulation: incumbent outcome (B,) and all-challenger outcomes (B, K)."""
    q = q_grid[rng.integers(len(q_grid), size=B)]
    y_inc = (rng.random(B) < q).astype(float)
    qk = np.clip(q[:, None] + shifts, lo, hi)
    x = (rng.random((B, K)) < qk).astype(float)
    return y_inc, x


# ----------------------------------------------------------------------------
# B1 state (batched E1b per-challenger processes, only the pulled arm moves)
# ----------------------------------------------------------------------------
class EfficacyState:
    """Per-challenger one-sided hedged capital K+ (m0 = 0.5), batched over (B, K)."""

    def __init__(self, B: int, K: int, m0: float = 0.5):
        self.B = B
        self.K = K
        self.m0 = m0
        self.cap = 0.5 / max(m0, EPS)
        self.log_kp = np.zeros((B, K))
        self.sum_x = np.zeros((B, K))
        self.sum_sq = np.zeros((B, K))
        self.cnt = np.zeros((B, K))
        self.lam = np.zeros((B, K))
        self.wins = np.zeros((B, K))
        self.disc = np.zeros((B, K))

    def log_global(self) -> np.ndarray:
        return logsumexp(self.log_kp, axis=1) - math.log(self.K)

    def update(self, pulled: np.ndarray, x: np.ndarray, y_inc: np.ndarray) -> None:
        """pulled (B,K) bool, x (B,K) challenger outcomes, y_inc (B,).  Only pulled arms move."""
        upd = pulled & (x != y_inc[:, None])
        m0 = self.m0
        term = 1.0 + self.lam * (x - m0)
        self.log_kp = self.log_kp + np.where(upd, np.log(np.maximum(term, 1e-300)), 0.0)
        cnt_new = self.cnt + 1.0
        sum_x_new = self.sum_x + x
        mu = (0.5 + sum_x_new) / (1.0 + cnt_new)
        sum_sq_new = self.sum_sq + (x - mu) ** 2
        sig2 = (0.25 + sum_sq_new) / (1.0 + cnt_new)
        lam_new = np.clip((mu - m0) / np.maximum(sig2, EPS), 0.0, self.cap)
        self.cnt = np.where(upd, cnt_new, self.cnt)
        self.sum_x = np.where(upd, sum_x_new, self.sum_x)
        self.sum_sq = np.where(upd, sum_sq_new, self.sum_sq)
        self.lam = np.where(upd, lam_new, self.lam)
        self.disc = self.disc + upd
        self.wins = self.wins + np.where(upd, x, 0.0)


def select_arm(rule: str, st: EfficacyState, t: int, rng: np.random.Generator,
               offsets: np.ndarray, eps_explore: float = 0.1, allowed: np.ndarray | None = None):
    """Predictable arm choice (B,) from the state at the start of step t.

    allowed (B,K) bool optionally masks out arms (exhausted arms in finite-bank replay).
    """
    B, K = st.log_kp.shape
    noise = 1e-9 * rng.random((B, K))
    if rule == "rr":
        return (t + offsets) % K
    if rule == "greedy":
        score = st.log_kp + noise
        if allowed is not None:
            score = np.where(allowed, score, -np.inf)
        arm = score.argmax(axis=1)
        rand_score = rng.random((B, K))
        if allowed is not None:
            rand_score = np.where(allowed, rand_score, -np.inf)
        rand_arm = rand_score.argmax(axis=1)
        explore = rng.random(B) < eps_explore
        return np.where(explore, rand_arm, arm)
    if rule == "ucb":
        phat = (st.wins + 1.0) / (st.disc + 2.0)
        bonus = np.sqrt(2.0 * math.log(t + 2.0) / (st.disc + 1.0))
        score = phat + bonus + noise
    elif rule == "thompson":
        score = rng.beta(st.wins + 1.0, st.disc - st.wins + 1.0)
    else:
        raise ValueError(rule)
    if allowed is not None:
        score = np.where(allowed, score, -np.inf)
    return score.argmax(axis=1)


def simulate_b1(rule: str, K: int, shifts: np.ndarray, q_grid: np.ndarray, budget: int,
                alpha: float, rng: np.random.Generator, eps_explore: float = 0.1,
                lo: float = 0.01, hi: float = 0.99) -> dict:
    """Infinite task supply.  Returns episodes at first rejection (inf if none within budget),
    distinct tasks, and the arm with the highest capital at that moment."""
    B = shifts.shape[0]
    audit = rule == "audit"
    per_step = (K + 1) if audit else 2
    max_steps = budget // per_step
    thr = math.log(1.0 / alpha)
    st = EfficacyState(B, K)
    rows = np.arange(B)
    offsets = rng.integers(K, size=B)
    done = np.zeros(B, dtype=bool)
    ep_rej = np.full(B, np.inf)
    tasks_rej = np.full(B, np.inf)
    best_arm = np.full(B, -1)
    all_pulled = np.ones((B, K), dtype=bool)
    for t in range(max_steps):
        y_inc, x = draw_task(rng, q_grid, B, K, shifts, lo, hi)
        if audit:
            pulled = all_pulled
        else:
            arm = select_arm(rule, st, t, rng, offsets, eps_explore)
            pulled = np.zeros((B, K), dtype=bool)
            pulled[rows, arm] = True
        st.update(pulled, x, y_inc)
        newly = (st.log_global() >= thr) & ~done
        if newly.any():
            ep_rej[newly] = (t + 1) * per_step
            tasks_rej[newly] = t + 1
            best_arm[newly] = st.log_kp.argmax(axis=1)[newly]
            done = done | newly
            if done.all():
                break
    return {"ep_rej": ep_rej, "tasks_rej": tasks_rej, "best_arm": best_arm}


