# B3 state
# ----------------------------------------------------------------------------
class FutilityState:
    """Per-challenger downward E5 mixture (aGRAPA + 4 fixed bets), only masked arms move."""

    def __init__(self, B: int, K: int, delta: float):
        self.B = B
        self.K = K
        self.delta = delta
        self.m = fu.boundary_m(delta)
        self.lams = fu.fixed_lambdas(delta)
        self.n_comp = 1 + len(self.lams)
        self.cap_ag = 0.5 / max(1.0 - self.m, EPS)
        self.log_comp = np.zeros((self.n_comp, B, K))
        self.lam_ag = np.zeros((B, K))
        self.sum_x = np.zeros((B, K))
        self.sum_sq = np.zeros((B, K))
        self.cnt = np.zeros((B, K))

    def log_e(self) -> np.ndarray:
        return logsumexp(self.log_comp, axis=0) - math.log(self.n_comp)

    def update(self, mask: np.ndarray, x: np.ndarray) -> None:
        """mask (B,K) bool; x (B,K) in [0,1] = (D+1)/2."""
        m = self.m
        f0 = np.log(np.maximum(1.0 - self.lam_ag * (x - m), 1e-300))
        self.log_comp[0] += np.where(mask, f0, 0.0)
        for j in range(len(self.lams)):
            fj = np.log(np.maximum(1.0 - self.lams[j] * (x - m), 1e-300))
            self.log_comp[j + 1] += np.where(mask, fj, 0.0)
        cnt_new = self.cnt + 1.0
        sum_x_new = self.sum_x + x
        mu_hat = (0.5 + sum_x_new) / (1.0 + cnt_new)
        sum_sq_new = self.sum_sq + (x - mu_hat) ** 2
        sigma2 = (0.25 + sum_sq_new) / (1.0 + cnt_new)
        raw = (m - mu_hat) / np.maximum(sigma2, EPS)
        lam_new = np.minimum(np.maximum(raw, 0.0), self.cap_ag)
        self.cnt = np.where(mask, cnt_new, self.cnt)
        self.sum_x = np.where(mask, sum_x_new, self.sum_x)
        self.sum_sq = np.where(mask, sum_sq_new, self.sum_sq)
        self.lam_ag = np.where(mask, lam_new, self.lam_ag)


def run_b3(rule: str, K: int, B: int, delta: float, alpha: float, budget: float, max_steps: int,
           get_x, rng: np.random.Generator, trace: bool = False) -> dict:
    """Generic B3 loop.  get_x(t) -> (B, K) array of X = (D+1)/2 for the fresh task of step t.

    Cost per step: audit K+1; drop 1 + (#active); focus 2.  A step is only taken if it fits in
    the budget.  Returns episodes/tasks at certification (inf if none) and episodes used.
    """
    thr = math.log(1.0 / alpha)
    st = FutilityState(B, K, delta)
    rows = np.arange(B)
    active = np.ones((B, K), dtype=bool)
    ep = np.zeros(B)
    done = np.zeros(B, dtype=bool)
    ep_cert = np.full(B, np.inf)
    tasks_cert = np.full(B, np.inf)
    steps_used = np.zeros(B)
    history = []
    for t in range(max_steps):
        if rule == "audit":
            cost = np.full(B, K + 1.0)
        elif rule == "drop":
            cost = 1.0 + active.sum(axis=1)
        else:
            cost = np.full(B, 2.0)
        alive = ~done & (ep + cost <= budget)
        if not alive.any():
            break
        x = get_x(t)
        if rule == "audit":
            mask = np.ones((B, K), dtype=bool) & alive[:, None]
        elif rule == "drop":
            mask = active & alive[:, None]
        else:
            score = np.where(active, st.log_e() + 1e-9 * rng.random((B, K)), np.inf)
            arm = score.argmin(axis=1)
            mask = np.zeros((B, K), dtype=bool)
            mask[rows, arm] = True
            mask = mask & active & alive[:, None]
        st.update(mask, x)
        ep = ep + np.where(alive, cost, 0.0)
        steps_used = steps_used + alive
        log_e = st.log_e()
        if rule == "audit":
            cert = log_e.min(axis=1) >= thr
        else:
            newly_dropped = active & (log_e >= thr) & alive[:, None]
            active = active & ~newly_dropped
            cert = ~active.any(axis=1)
            if trace:
                history.append(active.copy())
        newly = cert & alive
        if newly.any():
            ep_cert[newly] = ep[newly]
            tasks_cert[newly] = t + 1
            done = done | newly
    out = {"ep_cert": ep_cert, "tasks_cert": tasks_cert, "ep_used": ep, "steps_used": steps_used}
    if trace:
        out["active_history"] = history
    return out


def simulate_b3(rule: str, K: int, shifts: np.ndarray, q_grid: np.ndarray, delta: float,
                budget: int, alpha: float, rng: np.random.Generator, trace: bool = False,
                max_steps: int | None = None) -> dict:
    B = shifts.shape[0]
    if max_steps is None:
        max_steps = budget // 2

    def get_x(t):
        y_inc, xk = draw_task(rng, q_grid, B, K, shifts, 0.01, 1.0)
        return (xk - y_inc[:, None] + 1.0) / 2.0

    return run_b3(rule, K, B, delta, alpha, budget, max_steps, get_x, rng, trace=trace)


