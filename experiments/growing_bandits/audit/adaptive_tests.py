def load_bank(name: str, incumbent: str = "baseline"):
    """Returns (challenger_ids, Yc (K, n), y_inc (n,)) from a pool CSV (replicate 0)."""
    df = pd.read_csv(MATRICES / f"{name}.csv")
    df = df[df["replicate"] == 0]
    piv = df.pivot_table(index="arm_id", columns="task_id", values="success", aggfunc="mean")
    piv = piv.round().astype(float)
    ids = []
    for a in piv.index:
        if a != incumbent:
            ids.append(a)
    Yc = piv.loc[ids].to_numpy()
    y_inc = piv.loc[incumbent].to_numpy()
    return ids, Yc, y_inc


def replay_b1(rule: str, Yc: np.ndarray, y_inc: np.ndarray, orders: np.ndarray, alpha: float,
              rng: np.random.Generator, eps_explore: float = 0.1) -> dict:
    """Finite bank.  Each (challenger, task) cell is used at most once (per-arm pointer into the
    task order); the incumbent is paid once per distinct task (= max pointer).  rule in
    {greedy, rr, ucb, thompson, audit}.  Episodes = sum of pointers + max pointer."""
    K, n = Yc.shape
    B = orders.shape[0]
    thr = math.log(1.0 / alpha)
    st = EfficacyState(B, K)
    rows = np.arange(B)
    ptr = np.zeros((B, K), dtype=int)
    offsets = rng.integers(K, size=B)
    done = np.zeros(B, dtype=bool)
    ep_rej = np.full(B, np.inf)
    tasks_rej = np.full(B, np.inf)
    best_arm = np.full(B, -1)
    if rule == "audit":
        for t in range(n):
            task = orders[:, t]
            x = Yc[:, task].T
            yi = y_inc[task]
            st.update(np.ones((B, K), dtype=bool), x, yi)
            newly = (st.log_global() >= thr) & ~done
            if newly.any():
                ep_rej[newly] = (t + 1) * (K + 1)
                tasks_rej[newly] = t + 1
                best_arm[newly] = st.log_kp.argmax(axis=1)[newly]
                done = done | newly
        ep_used = np.where(done, ep_rej, n * (K + 1.0))
        tasks_used = np.where(done, tasks_rej, float(n))
        return {"ep_rej": ep_rej, "tasks_rej": tasks_rej, "best_arm": best_arm,
                "ep_used": ep_used, "tasks_used": tasks_used, "final_best": st.log_kp.argmax(axis=1)}
    ep_used = np.zeros(B)
    tasks_used = np.zeros(B)
    for step in range(K * n):
        allowed = ptr < n
        alive = ~done & allowed.any(axis=1)
        if not alive.any():
            break
        arm = select_arm(rule, st, step, rng, offsets, eps_explore, allowed=allowed)
        p = np.minimum(ptr[rows, arm], n - 1)
        task = orders[rows, p]
        x = np.zeros((B, K))
        x[rows, arm] = Yc[arm, task]
        yi = y_inc[task]
        pulled = np.zeros((B, K), dtype=bool)
        pulled[rows, arm] = alive
        st.update(pulled, x, yi)
        ptr[rows, arm] = ptr[rows, arm] + alive.astype(int)
        newly = (st.log_global() >= thr) & ~done & alive
        if newly.any():
            ep_rej[newly] = (ptr.sum(axis=1) + ptr.max(axis=1))[newly]
            tasks_rej[newly] = ptr.max(axis=1)[newly]
            best_arm[newly] = st.log_kp.argmax(axis=1)[newly]
            done = done | newly
    ep_used = np.where(done, ep_rej, ptr.sum(axis=1) + ptr.max(axis=1))
    tasks_used = np.where(done, tasks_rej, ptr.max(axis=1))
    return {"ep_rej": ep_rej, "tasks_rej": tasks_rej, "best_arm": best_arm,
            "ep_used": ep_used, "tasks_used": tasks_used, "final_best": st.log_kp.argmax(axis=1)}


def replay_b3(rule: str, Yc: np.ndarray, y_inc: np.ndarray, orders: np.ndarray, delta: float,
              alpha: float, rng: np.random.Generator) -> dict:
    """Finite bank: step t uses the task orders[:, t] (one fresh task per step, every cell used at
    most once).  Budget unlimited; the bank (n tasks) is the horizon."""
    K, n = Yc.shape
    B = orders.shape[0]
    D = Yc[:, orders] - y_inc[orders][None, :, :]  # (K, B, n)
    X = (np.transpose(D, (1, 0, 2)) + 1.0) / 2.0

    def get_x(t):
        return X[:, :, t]

    return run_b3(rule, K, B, delta, alpha, float("inf"), n, get_x, rng)


