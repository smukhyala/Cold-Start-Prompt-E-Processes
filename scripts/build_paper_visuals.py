"""Reproduce paper visuals from completed, saved results only (no experiments).

Run from any directory: <repo>/.venv/bin/python <this-file>
The original live PDF is reused byte for byte. Its original plotting source is
also copied to the output folder; see paper/figures/RESULTS_VISUALS.md for a
scratch-directory rerender command.
"""
from __future__ import annotations

import csv
import hashlib
import json
import math
import shutil
import statistics
from collections import Counter
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "paper" / "figures"
SOURCES: dict[str, str] = {}


def source(relative: str) -> Path:
    path = ROOT / relative
    SOURCES[relative] = hashlib.sha256(path.read_bytes()).hexdigest()
    return path


def read_json(relative: str):
    return json.loads(source(relative).read_text())


def read_csv(relative: str):
    with source(relative).open(newline="") as stream:
        return list(csv.DictReader(stream))


def close(actual, expected):
    assert math.isclose(actual, expected, rel_tol=1e-12, abs_tol=1e-12), (actual, expected)


def latex_table(name: str, columns: str, lines: list[str]):
    (OUT / name).write_text(
        "% Generated by build_paper_visuals.py from saved results.\n"
        "\\begin{tabular}{" + columns + "}\n"
        + "\n".join(lines) + "\n\\end{tabular}\n"
    )


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    live = read_json("results/paper/live_stopping/summary.json")
    evidence = read_json("results/paper/live_stopping/evidence.json")
    pairs = read_json("results/paper/live_stopping/pairs.json")
    terminal = read_json("results/paper/live_stopping/terminal.json")
    assert len(evidence) == len(pairs) == live["completed_pairs"] == 35
    assert [r["pair_index"] for r in evidence] == list(range(1, 36))
    assert [r["pair_index"] for r in pairs] == list(range(1, 36))
    assert live["threshold_efficacy"] == live["threshold_futility"] == 40
    assert terminal["decision"] == live["decision"] == "futility"
    assert terminal["reason"] == "statistical_boundary"
    assert not terminal["recovered_before_scheduling"]
    assert sum(r["baseline_success"] for r in pairs) == live["baseline_successes"] == 20
    assert sum(r["challenger_success"] for r in pairs) == live["challenger_successes"] == 16
    close((16 - 20) / 35, live["paired_difference"])
    for direction in ("efficacy", "futility"):
        threshold = math.log(live[f"threshold_{direction}"])
        crossings = [r["pair_index"] for r in evidence if r[f"log_{direction}"] >= threshold]
        assert crossings == ([] if direction == "efficacy" else [35])
        close(math.exp(evidence[-1][f"log_{direction}"]), live[f"final_{direction}"])
    assert 2 * (live["max_pairs"] - len(pairs)) == live["episodes_avoided_by_statistical_stop"] == 170
    # Confirm that the public-facing exports are the complete continuation.
    for filename in ("summary.json", "evidence.json", "pairs.json"):
        assert read_json(f"results/paper/live_stopping/{filename}") == read_json(
            f"results/paper/live_stopping/continuation/{filename}"
        )
    for filename in ("independent_statistical_audit.json", "independent_operational_audit.json"):
        source(f"results/paper/live_stopping/continuation/{filename}")
    source("results/paper/live_stopping/README.md")
    source("docs/paper/LIVE_STOPPING_RESULTS.md")
    live_pdf = source("results/paper/live_stopping/live_stopping_continuation.pdf")
    shutil.copyfile(live_pdf, OUT / live_pdf.name)
    plot_source = source("experiments/growing_bandits/empirical/plot_live_stopping_continuation.py")
    shutil.copyfile(plot_source, OUT / "plot_live_stopping_source.py")

    prompt = read_json("results/paper/public_replay_02/summary.json")
    prompt_rows = read_csv("results/paper/public_replay_02/settings.csv")
    mizrahi = read_json("results/paper/mizrahi_replay/summary.json")
    mizrahi_rows = mizrahi["setting_rows"]
    selection = []
    for name, reference, rows, summary, ci_key, expected in [
        ("PromptEval", "Positional row 0", prompt_rows, prompt, "mean_shrinkage_ci", (5.02, 0.54)),
        ("Mizrahi", "Original benchmark template", mizrahi_rows, mizrahi, "shrinkage_ci95", (22.96, 15.04)),
    ]:
        assert len(rows) == summary["settings"]
        assert dict(Counter(r["decision"] for r in rows)) == summary["decisions"]
        search = statistics.mean(float(r["search_gain"]) for r in rows)
        heldout = statistics.mean(float(r["heldout_gain"]) for r in rows)
        close(search - heldout, summary["mean_shrinkage"])
        assert (round(100 * search, 2), round(100 * heldout, 2)) == expected
        selection.append(dict(dataset=name, reference=reference, settings=len(rows),
                              search_gain_pp=100 * search, heldout_gain_pp=100 * heldout,
                              shrinkage_pp=100 * summary["mean_shrinkage"],
                              shrinkage_ci_low_pp=100 * summary[ci_key][0],
                              shrinkage_ci_high_pp=100 * summary[ci_key][1]))
    close(selection[1]["search_gain_pp"], 100 * mizrahi["mean_search_gain"])
    close(selection[1]["heldout_gain_pp"], 100 * mizrahi["mean_heldout_gain"])
    with (OUT / "prompt_selection_bias_data.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(selection[0]))
        writer.writeheader()
        writer.writerows(selection)

    with plt.rc_context({"font.family": "DejaVu Sans", "font.size": 10.5,
                         "pdf.fonttype": 42, "ps.fonttype": 42,
                         "axes.spines.top": False, "axes.spines.right": False}):
        fig, ax = plt.subplots(figsize=(6.5, 3.65))
        fig.subplots_adjust(left=.115, right=.985, bottom=.32, top=.88)
        width = .29
        for offset, key, label, color, hatch in [
            (-width / 2, "search_gain_pp", "Selection examples", ".3", None),
            (width / 2, "heldout_gain_pp", "Separate evaluation examples", ".88", "///"),
        ]:
            bars = ax.bar([i + offset for i in range(2)], [r[key] for r in selection],
                          width=width, label=label, color=color, hatch=hatch,
                          edgecolor=".2", linewidth=.6, zorder=3)
            ax.bar_label(bars, labels=[f"{r[key]:.2f}" for r in selection], padding=4, fontsize=10.5)
        ax.set(ylim=(0, 27), xlim=(-.6, 1.6), ylabel="Mean improvement\n(percentage points)")
        ax.set_yticks([0, 5, 10, 15, 20, 25])
        ax.set_xticks([0, 1], ["PromptEval\nPositional reference: row 0",
                              "Mizrahi\nOriginal benchmark template"])
        ax.tick_params(axis="x", length=0, pad=8)
        ax.grid(axis="y", color=".9", linewidth=.5, zorder=0)
        ax.legend(loc="lower center", bbox_to_anchor=(.5, 1.02), ncol=2,
                  frameon=False, fontsize=10, handlelength=1.6, columnspacing=1.7)
        for i, row in enumerate(selection):
            ax.text(i, -.36,
                    f"Shrinkage: {row['shrinkage_pp']:.2f} pp\n"
                    f"95% CI [{row['shrinkage_ci_low_pp']:.2f}, {row['shrinkage_ci_high_pp']:.2f}]",
                    transform=ax.get_xaxis_transform(), ha="center", va="top", fontsize=10)
        fig.savefig(OUT / "prompt_selection_bias.pdf", metadata={"CreationDate": None, "ModDate": None})
        plt.close(fig)

    fixed = read_json("results/paper/prospective_linear/summary.json")
    sampled = read_json("results/paper/prospective_sampled_linear/summary.json")
    for folder, summary in [("prospective_linear", fixed), ("prospective_sampled_linear", sampled)]:
        rows = read_csv(f"results/paper/{folder}/tasks.csv")
        assert len(rows) == summary["paired_prefix_tasks"] == summary["planned_tasks"]
        close(statistics.mean(int(r["challenger_success"]) - int(r["incumbent_success"]) for r in rows),
              summary["paired_gain"])
    swe = read_json("results/paper/public_replay_03/summary.json")
    tb = read_json("results/paper/public_replay_01/summary.json")
    tb_gains = read_csv("results/paper/public_replay_01/gains.csv")
    tb_futility = read_csv("results/paper/public_replay_01/r3_futility.csv")
    assert tb["confirmation"]["primary_cross_task"] == tb["r3_crossings"] == 0
    assert all(int(r["futility_first_cross"]) == 0 for r in tb_futility)
    assert tb["tasks"] == 68 and len(tb["arms"]) == 3
    for pair in swe["pairs"]:
        close((pair["challenger_resolved"] - pair["reference_resolved"]) / pair["common_tasks"], pair["paired_gain"])
    for filename in ("PUBLIC_REPLAY_PREREG_01.md", "PUBLIC_REPLAY_PREREG_02.md",
                     "PUBLIC_REPLAY_PREREG_03.md", "MIZRAHI_REPLAY_PROTOCOL.md"):
        source(f"docs/paper/{filename}")

    def cross(value):
        return str(value) if value else r"\textemdash"

    lines = [r"\toprule", r"Comparison & $N$ & $n$ & Gain (pp) & $\tau^+$ & $\tau^-$ & Decision\\",
             r"\midrule", r"\multicolumn{7}{@{}l}{\emph{Prospective live stopping (amended continuation)}}\\",
             f"Linear, sampled public bank & {live['max_pairs']} & {live['completed_pairs']} & "
             f"${100 * live['paired_difference']:+.2f}$ & \\textemdash & {live['first_crossing_pair']} & Futility\\\\",
             r"\addlinespace", r"\multicolumn{7}{@{}l}{\emph{Prospectively collected full grids}}\\"]
    for name, summary in [("Linear, fixed public bank", fixed), ("Linear, generated profile edits", sampled)]:
        lines.append(f"{name} & {summary['planned_tasks']} & {summary['paired_prefix_tasks']} & "
                     f"${100 * summary['paired_gain']:+.2f}$ & {cross(summary['efficacy_first_crossing'])} & "
                     f"{cross(summary['futility_first_crossing'])} & Futility\\\\")
    lines.extend([r"\addlinespace", r"\multicolumn{7}{@{}l}{\emph{Historical replays}}\\"])
    for name, pair in zip(["SWE-bench, GPT-4", "SWE-bench, Claude 3 Opus"], swe["pairs"]):
        lines.append(f"{name} & {pair['common_tasks']} & {pair['common_tasks']} & "
                     f"${100 * pair['paired_gain']:+.2f}$ & {pair['prespecified_cross_task']} & n/a & Efficacy\\\\")
    gains_by_arm = {r["arm"]: float(r["trial0_gain"]) for r in tb_gains}
    gains = [100 * gains_by_arm[arm] for arm in
             ("Capy__Claude-Opus-4.6", "Terminus-KIRA__Claude-Opus-4.6")]
    lines.extend([f"Terminal-Bench, two scaffolds & {tb['tasks']} & {tb['tasks']} & "
                  f"${gains[0]:+.2f}/{gains[1]:+.2f}$ & \\textemdash & \\textemdash & Unresolved\\\\", r"\bottomrule"])
    latex_table("experimental_results_table.tex", "@{}lrrrcc l@{}", lines)

    budgets = [int(r["n_search"]) for r in prompt_rows]
    assert (min(budgets), max(budgets), statistics.median(budgets)) == (50, 767, 86)
    assert {r["search_tasks"] for r in mizrahi_rows} == {50}
    ks = [r["K"] for r in mizrahi_rows]
    lines = [r"\toprule", r"Dataset / reference & Settings & $K$ & Search $N$ & Efficacy & Futility & Unresolved\\", r"\midrule"]
    for name, summary, k, budget in [
        (r"\shortstack[l]{PromptEval /\\positional row 0}", prompt, "99", f"{min(budgets)}--{max(budgets)}"),
        (r"\shortstack[l]{Mizrahi /\\original template}", mizrahi, f"{min(ks)}--{max(ks)}", "50"),
    ]:
        decisions = summary["decisions"]
        lines.append(f"{name} & {summary['settings']} & {k} & {budget} & {decisions['efficacy']} & "
                     f"{decisions['futility']} & {decisions['unresolved']}\\\\")
        if summary is prompt:
            lines.append(r"\addlinespace")
    lines.append(r"\bottomrule")
    latex_table("prompt_decisions_table.tex", "@{}lrrrrrr@{}", lines)
    (OUT / "results_visuals_sources.json").write_text(json.dumps({
        "description": "SHA-256 of exact saved inputs; no experiments, resampling, or new inferential analysis.",
        "sources": dict(sorted(SOURCES.items())),
        "checks": "Saved counts, gains, live boundaries, continuation parity, budgets and decision totals agree.",
        "selection": selection,
    }, indent=2) + "\n")
    print("Verified saved results; reused live PDF; wrote selection PDF, two tables, plotted data and provenance.")


if __name__ == "__main__":
    main()
